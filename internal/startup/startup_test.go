package startup

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestApplyEntryCreatesAndRemovesOwnedEntry(t *testing.T) {
	entry, config := startupTestPaths(t)
	write := func(path string) error { return os.WriteFile(path, []byte("generated by Nexora\n"), 0600) }
	if err := applyEntry(true, entry, config, write); err != nil {
		t.Fatal(err)
	}
	markerPath := filepath.Join(config, "startup-managed")
	marker, err := os.ReadFile(markerPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(marker), entry+"\n") || len(strings.Fields(string(marker))) != 2 {
		t.Fatalf("unexpected ownership marker: %q", marker)
	}
	if err := applyEntry(false, entry, config, write); err != nil {
		t.Fatal(err)
	}
	assertMissing(t, entry)
	assertMissing(t, markerPath)
}

func TestApplyEntryPreservesUnownedAndModifiedEntries(t *testing.T) {
	t.Run("unowned", func(t *testing.T) {
		entry, config := startupTestPaths(t)
		want := []byte("owned by the user\n")
		if err := os.MkdirAll(filepath.Dir(entry), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(entry, want, 0600); err != nil {
			t.Fatal(err)
		}
		write := func(path string) error { return os.WriteFile(path, []byte("replacement"), 0600) }
		if err := applyEntry(true, entry, config, write); err == nil || !strings.Contains(err.Error(), "not managed by Nexora") {
			t.Fatalf("applyEntry() error = %v, want unowned-entry error", err)
		}
		assertContent(t, entry, want)
		if err := applyEntry(false, entry, config, write); err != nil {
			t.Fatalf("disabling startup errored for an unowned entry: %v", err)
		}
	})

	t.Run("modified managed", func(t *testing.T) {
		entry, config := startupTestPaths(t)
		write := func(path string) error { return os.WriteFile(path, []byte("generated by Nexora\n"), 0600) }
		if err := applyEntry(true, entry, config, write); err != nil {
			t.Fatal(err)
		}
		changed := []byte("changed by user\n")
		if err := os.WriteFile(entry, changed, 0600); err != nil {
			t.Fatal(err)
		}
		for _, enabled := range []bool{true, false} {
			if err := applyEntry(enabled, entry, config, write); err == nil || !strings.Contains(err.Error(), "changed since Nexora created it") {
				t.Fatalf("applyEntry(%v) error = %v, want changed-entry error", enabled, err)
			}
			assertContent(t, entry, changed)
			if _, err := os.Stat(filepath.Join(config, "startup-managed")); err != nil {
				t.Fatalf("marker lost after preserving modified entry: %v", err)
			}
		}
	})
}

func TestApplyEntryRestoresNewEntryWhenOwnershipCannotBeRecorded(t *testing.T) {
	entry, config := startupTestPaths(t)
	write := func(path string) error {
		if err := os.WriteFile(path, []byte("generated by Nexora\n"), 0600); err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(config), 0700); err != nil {
			return err
		}
		return os.WriteFile(config, []byte("prevents config directory creation"), 0600)
	}
	if err := applyEntry(true, entry, config, write); err == nil || !strings.Contains(err.Error(), "cannot create Nexora settings folder") {
		t.Fatalf("applyEntry() error = %v, want ownership-storage error", err)
	}
	assertMissing(t, entry)
	if _, err := os.Stat(config); err != nil {
		t.Fatalf("injected config path was unexpectedly removed: %v", err)
	}
}

func startupTestPaths(t *testing.T) (string, string) {
	t.Helper()
	root := t.TempDir()
	entry := filepath.Join(root, "startup", "Nexora-entry")
	config := filepath.Join(root, "config", "Nexora")
	return entry, config
}

func assertContent(t *testing.T, path string, want []byte) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil || string(got) != string(want) {
		t.Fatalf("file content = %q, %v; want %q", got, err, want)
	}
}

func assertMissing(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Lstat(path); !os.IsNotExist(err) {
		t.Fatalf("expected %s to be absent, got %v", path, err)
	}
}
